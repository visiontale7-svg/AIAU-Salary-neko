function unit(
  id: string,
  turnOrdinal: number,
  speaker: Speaker,
  kind: SemanticUnit["kind"],
  label: string,
  fullText: string,
  acts: DialogueAct[],
  options: Partial<SemanticUnit> = {},
): SemanticUnit {
  const turnId = `T${String(turnOrdinal).padStart(2, "0")}`;
  return {
    id,
    turnId,
    turnOrdinal,
    speaker,
    kind,
    label,
    fullText,
    acts,
    importance: kind === "anchor" ? 0.92 : kind === "operation" ? 0.25 : 0.65,
    provenance: "fixture",
    sourceSpans: [span(`${turnId}-${id}`, fullText)],
    modeIds: modeIds[id] ?? [],
    ...options,
  };
}

